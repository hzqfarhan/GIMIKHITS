import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
const origin=process.argv[2]||'http://localhost:5173';
if(!['localhost','127.0.0.1'].includes(new URL(origin).hostname))throw new Error('This rehearsal check may only reset a local development server.');
const key=readFileSync('.dev.vars','utf8').match(/^ORGANISER_KEY=(.+)$/m)?.[1].trim();
let checks=0;
async function request(action,body={},cookie='',expected=200){
  const r=await fetch(`${origin}/api/event`,{method:action?'POST':'GET',headers:{'Content-Type':'application/json',Origin:origin,Cookie:cookie},...(action?{body:JSON.stringify({action,...body})}:{})});
  const data=await r.json();assert.equal(r.status,expected,data.error);checks++;
  return {data,cookie:r.headers.get('set-cookie')?.split(';')[0]||cookie};
}
await request('boost',{value:10},'',401);
await request('login',{key:'invalid'},'',401);
const operator=(await request('login',{key})).cookie;
await request('reset',{},operator);
await request('settings',{value:0},operator,400);
await request('settings',{value:20,videoUrl:'javascript:alert(1)'},operator,400);
await request('settings',{value:20,videoUrl:''},operator);
const audience=await request('activate');assert.equal(audience.data.audience,1);
const duplicate=await request('activate',{},audience.cookie);assert.equal(duplicate.data.audience,1);assert.equal(duplicate.data.activated,true);
await request('pause',{},operator);
const paused=await request('activate');assert.equal(paused.data.audience,1);assert.equal(paused.data.activated,false);
await request('pause',{},operator);
const boost=await request('boost',{value:10},operator);assert.equal(boost.data.total,11);assert.equal(boost.data.audience,1);
await request('unlock',{},operator);let state=(await request(null)).data;assert.equal(state.total,20);assert.equal(state.phase,'ready');assert.equal(state.operator,false);assert.equal(state.boost,undefined);
await request('launch',{code:state.code},'',401);
await request('launch',{code:'invalid'},operator,400);
const launch=await request('launch',{code:state.code},operator);assert.equal(launch.data.phase,'launching');assert.ok(launch.data.launchedAt);
const frozen=await request('activate');assert.equal(frozen.data.total,20);assert.equal(frozen.data.audience,1);
await request('launch',{code:state.code},operator,409);
const oldEpoch=state.epoch;
await request('reset',{},operator);state=(await request(null,{},audience.cookie)).data;assert.notEqual(state.epoch,oldEpoch);assert.equal(state.activated,false);assert.equal(state.total,0);
await request('settings',{value:5,videoUrl:''},operator);
await Promise.all(Array.from({length:20},()=>request('activate')));
state=(await request(null)).data;assert.equal(state.audience,5,'Concurrent taps must not overshoot the target');assert.equal(state.phase,'ready');
const csrf=await fetch(`${origin}/api/event`,{method:'POST',headers:{Origin:'https://other-site.example','Content-Type':'application/json',Cookie:operator},body:JSON.stringify({action:'reset'})});assert.equal(csrf.status,403);checks++;
await request('reset',{},operator);await request('settings',{value:100,videoUrl:''},operator);
const finalState=(await request(null)).data;assert.equal(finalState.total,0);assert.equal(finalState.quota,100);
assert.equal(finalState.links.main,`${origin}/`);
assert.equal(finalState.links.qr,`${origin}/qr`);
assert.equal(finalState.links.bypass,`${origin}/bypass`);
assert.equal(finalState.links.audience,`${origin}/audience`);
const malformed=await fetch(`${origin}/api/event`,{method:'POST',headers:{Origin:origin,'Content-Type':'application/json'},body:'invalid json'});assert.equal(malformed.status,400);checks++;
const forged=operator.replace(/.$/,'x');
await request('boost',{value:1},forged,401);
await request('logout',{},operator);
console.log(`PASS: ${checks} HTTP checks; duplicate protection, pause/resume, authenticated controls, boost, code validation, launch freeze, reset, concurrent target enforcement, and cross-origin rejection. Restored a fresh 100-activation rehearsal.`);
